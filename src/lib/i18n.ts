const DICTS: Record<Lang, Record<Key, string>> = { ru: RU as Record<Key, string>, uk: UK, en: EN };

/** "system" → язык ОС; всё незнакомое → английский. */
export function resolveLang(setting: string | undefined): Lang {
  if (setting === "ru" || setting === "uk" || setting === "en") return setting;
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("ru")) return "ru";
  if (nav.startsWith("uk")) return "uk";
  return "en";
}

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): T {
  const dict = DICTS[lang];
  return (key, vars) => {
    let s = dict[key] ?? RU[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

/** Локальные преобразования регистра (кнопка «Регистр» в оверлее). */
export const FORMATS = ["sentence", "lower", "upper", "title", "toggle"] as const;
export type Fmt = (typeof FORMATS)[number];
export const FMT_KEYS: Record<Fmt, Key> = {
  sentence: "fmt.sentence",
  lower: "fmt.lower",
  upper: "fmt.upper",
  title: "fmt.title",
  toggle: "fmt.toggle",
};

/** `format:upper` → «upper»; для обычных стилей — null. */
export function parseFmt(id: string): Fmt | null {
  const f = id.startsWith("format:") ? id.slice(7) : "";
  return (FORMATS as readonly string[]).includes(f) ? (f as Fmt) : null;
}

/** Имя записи истории, у которой нет стиля: раскладка или регистр. */
export function actionName(t: T, id: string): string | null {
  if (id === "layout") return t("fx.layout");
  const f = parseFmt(id);
  return f ? t(FMT_KEYS[f]) : null;
}
